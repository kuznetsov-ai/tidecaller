export const CARD_LIST = LIST;
export const CARDS: Record<string, CardDef> = Object.fromEntries(LIST.map((c) => [c.id, c]));

export function effectsOf(def: CardDef, upgraded: boolean): Effect[] {
  return upgraded && def.up ? def.up : def.effects;
}

export function cardRate(id: string): number {
  const c = CARDS[id];
  if (!c) return 0;
  if (c.rate) return c.rate;
  if (c.rarity === 'rare') return 8;
  if (c.rarity === 'uncommon') return 6;
  if (c.rarity === 'common') return 4;
  if (c.rarity === 'starter') return 3;
  return 0;
}

export function movesTide(effects: Effect[]): boolean {
  for (const e of effects) {
    if (e.op === 'tide' || e.op === 'tideSet' || e.op === 'tideChoose') return true;
    if (e.op === 'conditional' && (movesTide(e.effects) || (e.else ? movesTide(e.else) : false))) return true;
  }
  return false;
}

export const LOCKABLE_CARDS = ['moonhook', 'leviathan', 'still_water', 'lighthouse'];

export function poolFor(
  rarity: Rarity,
  character: CardClass | 'brine' | 'keel' | 'moth',
  unlocked: string[],
): CardDef[] {
  return LIST.filter(
    (c) =>
      c.rarity === rarity &&
      (c.class === 'any' || c.class === character) &&
      (!c.locked || unlocked.includes(c.id)),
  );
}

